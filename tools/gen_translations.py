    for lang, table in L.items():
        missing, extra = keys - set(table), set(table) - keys
        assert not missing and not extra, f"{lang}: missing {sorted(missing)} extra {sorted(extra)}"
    for lang, table in L.items():
        with open(os.path.join(OUT, f"{lang}.json"), "w", encoding="utf-8") as f:
            json.dump(nest({**COMMON, **table}), f, ensure_ascii=False, indent=2)
            f.write("\n")
    print(f"wrote {len(L)} languages: {', '.join(L)}")


